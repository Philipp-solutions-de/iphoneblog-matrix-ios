#!/usr/bin/env bash
# Turn brand.env into App/Generated/Brand.swift and generate the Xcode project.
#   scripts/configure.sh
# Run it after a checkout and after every change to brand.env or project.yml.
set -euo pipefail

here="$(cd "$(dirname "$0")/.." && pwd)"
cd "$here"

set -a
# shellcheck source=../brand.env
. ./brand.env
set +a
TEAM_ID="${APPLE_TEAM_ID:-}"

if (( ${#APP_DISPLAY_NAME} > 12 )); then
    echo "configure.sh: APP_DISPLAY_NAME is longer than 12 characters" >&2
    exit 1
fi

scheme="${OAUTH_REDIRECT_URI%%:*}"
mkdir -p App/Generated
cat > App/Generated/Brand.swift <<EOF
// Generated by scripts/configure.sh from brand.env. Do not edit.

import Foundation

enum Brand {
    static let appName = "$APP_DISPLAY_NAME"
    static let bundleID = "$BUNDLE_ID"
    static let appGroupID = "$APP_GROUP_ID"
    static let notificationExtensionBundleID = "$BUNDLE_ID.nse"

    static let serverName = "$MATRIX_SERVER_NAME"
    static let homeserverURL = "$MATRIX_HOMESERVER_URL"

    static let oauthClientURI = "$OAUTH_CLIENT_URI"
    static let oauthRedirectURI = "$OAUTH_REDIRECT_URI"
    static let oauthRedirectScheme = "$scheme"
    static let oauthLogoURI = "$OAUTH_LOGO_URI"
    static let oauthTermsURI = "$OAUTH_TOS_URI"
    static let oauthPolicyURI = "$OAUTH_POLICY_URI"

    static let blogRoomAlias = "$BLOG_ROOM_ALIAS"
    static let oneRoomAlias = "$ONE_ROOM_ALIAS"
    static let blogAPIURL = "$BLOG_API_URL"
    static let oneOfferURL = "$ONE_OFFER_URL"

    static let pushGatewayURL = "$PUSH_GATEWAY_URL"
    static let pusherAppID = "$BUNDLE_ID.ios.prod"
}
EOF

export APP_DISPLAY_NAME TEAM_ID BUNDLE_ID APP_GROUP_ID OAUTH_REDIRECT_SCHEME="$scheme"
xcodegen --quiet --spec project.yml
echo "configure.sh: done"
