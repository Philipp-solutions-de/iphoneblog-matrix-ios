#!/usr/bin/env python3
"""Apply the iphoneblog brand to an Element X source tree.

Usage: brand.py <upstream-tree> <brand.env>

Every edit asserts that it found what it expects. When upstream moves a line, this
script stops with a clear message instead of building an app that is half Element.
"""

import pathlib
import re
import shlex
import sys


def fail(msg):
    sys.exit(f"brand.py: {msg}")


def load_env(path):
    env = {}
    for line in pathlib.Path(path).read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        key, _, value = line.partition("=")
        env[key] = shlex.split(value)[0] if value else ""
    return env


def sub_once(text, pattern, repl, what, flags=re.MULTILINE):
    new, n = re.subn(pattern, repl, text, flags=flags)
    if n == 0:
        fail(f"{what}: pattern not found: {pattern}")
    return new


def hex_to_int(color):
    return "0x" + color.lstrip("#").upper()


def darker(color, factor=0.75):
    c = color.lstrip("#")
    r, g, b = (int(c[i:i + 2], 16) for i in (0, 2, 4))
    return "#%02X%02X%02X" % (int(r * factor), int(g * factor), int(b * factor))


def main():
    if len(sys.argv) != 3:
        fail("usage: brand.py <upstream-tree> <brand.env>")
    root = pathlib.Path(sys.argv[1])
    env = load_env(sys.argv[2])

    if len(env["APP_DISPLAY_NAME"]) > 12:
        fail("APP_DISPLAY_NAME is longer than 12 characters; the home screen cuts it")

    # 1. app.yml: name, identifiers, team. Element Classic migration points at our own
    #    group and a keychain service that never exists, so it finds nothing.
    app_yml = root / "app.yml"
    text = app_yml.read_text()
    team = env["TEAM_ID"]
    values = {
        "APP_DISPLAY_NAME": env["APP_DISPLAY_NAME"],
        "PRODUCTION_APP_NAME": env["APP_DISPLAY_NAME"],
        "APP_GROUP_IDENTIFIER": env["APP_GROUP_ID"],
        "BASE_BUNDLE_IDENTIFIER": env["BUNDLE_ID"],
        "DEVELOPMENT_TEAM": team,
        "CLASSIC_APP_GROUP_IDENTIFIER": env["APP_GROUP_ID"],
        "CLASSIC_APP_KEYCHAIN_SERVICE_IDENTIFIER": env["BUNDLE_ID"] + ".no-classic-app",
        "CLASSIC_APP_KEYCHAIN_ACCESS_GROUP_IDENTIFIER": f'"$(DEVELOPMENT_TEAM).{env["BUNDLE_ID"]}.no-classic-app"',
        "CLASSIC_APP_DEEP_LINK_URL": f'"{env["BUNDLE_ID"]}://no-classic-app"',
    }
    for key, value in values.items():
        text = sub_once(text, rf"^(\s+{key}:).*$", rf"\g<1> {value}", f"app.yml {key}")
    app_yml.write_text(text)

    # 2. Associated domains: Element's own domains and matrix.to out, the Matrix host in.
    host = env["MATRIX_SERVER_NAME"]
    target_yml = root / "ElementX/SupportingFiles/target.yml"
    text = target_yml.read_text()
    text = sub_once(text,
                    r"(com\.apple\.developer\.associated-domains:\n)(?:\s+(?:#\s*)?- (?:applinks|webcredentials):.*\n)+",
                    rf"\g<1>        - applinks:{host}\n        - webcredentials:{host}\n",
                    "target.yml associated domains")
    if "element.io" in text.split("associated-domains")[1].split("com.apple.developer.usernotifications")[0]:
        fail("target.yml still lists an element.io domain")
    target_yml.write_text(text)

    # 3. Secrets: no analytics, no crash reports, no rageshake, no map key.
    secrets = root / "Components/Secrets/Secrets.swift"
    text = secrets.read_text()
    text, n = re.subn(r'(static let \w+: String\?) = ".*"', r"\1 = nil", text)
    if n == 0:
        fail("Secrets.swift: no secrets found to clear")
    secrets.write_text(text)

    # 4. Strings that show Element's name in the UI the trial reaches.
    sound_keys = ("screen_notification_settings_sound_element_default",
                  "screen_notification_settings_sound_element_fade")
    changed = 0
    for strings in (root / "ElementX/Resources/Localizations").glob("*.lproj/Localizable.strings"):
        text = strings.read_text()
        new = text
        for key in sound_keys:
            new = re.sub(rf'^("{key}" = ")Element\s*(.*";)$', r"\1\2", new, flags=re.MULTILINE)
        if new != text:
            strings.write_text(new)
            changed += 1
    if changed == 0:
        fail("Localizable.strings: sound names not found")

    # 5. Brand constants for the hooks in overlay/ElementX/Sources/Iphoneblog.
    swift = f"""//
// Generated by scripts/brand.py from brand.env. Do not edit.
//
// SPDX-License-Identifier: AGPL-3.0-only
//

#if IS_MAIN_APP

import Foundation

enum IphoneblogBrand {{
    static let matrixServerName = "{host}"
    static let matrixBaseURL = URL(string: "{env["MATRIX_BASE_URL"]}")!
    static let pushGatewayBaseURL = URL(string: "{env["PUSH_GATEWAY_BASE_URL"]}")!
    static let websiteURL = URL(string: "{env["WEBSITE_URL"]}")!
    static let logoURL = URL(string: "{env["LOGO_URL"]}")!
    static let copyrightURL = URL(string: "{env["COPYRIGHT_URL"]}")!
    static let termsURL = URL(string: "{env["TERMS_URL"]}")!
    static let privacyURL = URL(string: "{env["PRIVACY_URL"]}")!

    static let brandColor: UInt32 = {hex_to_int(env["BRAND_COLOR"])}
    static let brandColorDarkText: UInt32 = {hex_to_int(env["BRAND_COLOR_DARK_TEXT"])}
    static let brandColorPressed: UInt32 = {hex_to_int(darker(env["BRAND_COLOR_DARK_TEXT"]))}
    static let brandColorLightOnDark: UInt32 = {hex_to_int(env["BRAND_COLOR_LIGHT_ON_DARK"])}
}}

#endif
"""
    out = root / "ElementX/Sources/Iphoneblog/IphoneblogBrand.swift"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(swift)

    # 6. Global accent colour of the asset catalog.
    def comp(color):
        c = color.lstrip("#")
        return {"red": f"0x{c[0:2]}", "green": f"0x{c[2:4]}", "blue": f"0x{c[4:6]}", "alpha": "1.000"}

    import json
    accent = {
        "colors": [
            {"color": {"color-space": "srgb", "components": comp(env["BRAND_COLOR_DARK_TEXT"])}, "idiom": "universal"},
            {"appearances": [{"appearance": "luminosity", "value": "dark"}],
             "color": {"color-space": "srgb", "components": comp(env["BRAND_COLOR_LIGHT_ON_DARK"])}, "idiom": "universal"},
        ],
        "info": {"author": "xcode", "version": 1},
    }
    accent_path = root / "ElementX/Resources/Assets.xcassets/colors/accent-color.colorset/Contents.json"
    if not accent_path.exists():
        fail("accent-color.colorset is gone; check ASSETCATALOG_COMPILER_GLOBAL_ACCENT_COLOR_NAME in app.yml")
    accent_path.write_text(json.dumps(accent, indent=2) + "\n")

    print("brand.py: done")


if __name__ == "__main__":
    main()
